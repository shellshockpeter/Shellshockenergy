#!/usr/bin/env python3
"""Trace the tub silhouette from public/tub.png (alpha) into src/video1/tubSilhouette.ts (SVG path, viewBox 850x1100).
   python3 scripts/trace_tub.py   (needs opencv-python-headless, pillow, numpy)"""
import os
import cv2
import numpy as np
from PIL import Image
from scipy import ndimage as ndi

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
im = Image.open(os.path.join(ROOT, 'public', 'tub.png')).convert('RGBA')
W, H = im.size
a = np.asarray(im.getchannel('A'))
mask = (a > 128).astype('uint8')
mask = cv2.morphologyEx(mask, cv2.MORPH_CLOSE, np.ones((9, 9), np.uint8))
cs, _ = cv2.findContours(mask, cv2.RETR_EXTERNAL, cv2.CHAIN_APPROX_NONE)
c = max(cs, key=cv2.contourArea)
hull = cv2.convexHull(c)[:, 0, :].astype(float)  # the tub is convex: ignore label art / lid notches
# resample the hull densely, then smooth so the neon line is clean
pts = []
for i in range(len(hull)):
    p0, p1 = hull[i], hull[(i + 1) % len(hull)]
    n = max(1, int(np.hypot(*(p1 - p0)) / 5))
    for t in range(n):
        pts.append(p0 + (p1 - p0) * t / n)
c = np.array(pts)
c = np.stack([ndi.gaussian_filter1d(c[:, k], 9, mode='wrap') for k in (0, 1)], axis=1)
ap = cv2.approxPolyDP(c.astype(np.float32).reshape(-1, 1, 2), 1.2, True)[:, 0, :]
d = 'M' + 'L'.join(f'{x:.1f} {y:.1f}' for x, y in ap) + 'Z'

# lid seam: a gentle curve across the tub just under the lid
seam_y = 0.235 * H
row = np.where(mask[int(seam_y)] > 0)[0]
x0, x1 = row.min() + 0.012 * W, row.max() - 0.012 * W
seam = f'M{x0:.1f} {seam_y:.1f}Q{(x0 + x1) / 2:.1f} {seam_y + 26:.1f} {x1:.1f} {seam_y:.1f}'
out = os.path.join(ROOT, 'src', 'video1', 'tubSilhouette.ts')
with open(out, 'w') as f:
    f.write('// GENERATED by scripts/trace_tub.py from public/tub.png\n')
    f.write(f'export const TUB_VIEWBOX = {{w: {W}, h: {H}}};\n')
    f.write(f"export const TUB_OUTLINE_PATH =\n\t'{d}';\n")
    f.write(f"export const TUB_SEAM_PATH = '{seam}';\n")
print('wrote', os.path.relpath(out, ROOT), f'({len(ap)} points, {W}x{H})')
