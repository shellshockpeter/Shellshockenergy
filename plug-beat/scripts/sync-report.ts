/**
 * Writes sync-report.md: every Video1 event with its time, its frame AFTER syncOffsetFrames,
 * and the spoken word it is meant to hit. Reads the same timeline the composition renders from.
 *
 *   npm run sync-report                      # offset = default (-2)
 *   npx tsx scripts/sync-report.ts -3        # try another offset
 */
import {writeFileSync} from 'node:fs';
import {revealStartFrame} from '../src/video1/NineBoard';
import path from 'node:path';
import {
	BOARD_REVEAL,
	BOARD_TILES,
	BUDGET,
	CHIP,
	CUTS,
	DEFAULT_SYNC_OFFSET_FRAMES,
	FPS,
	SOURCE_FRAMES,
	TIMELINE,
	TOTAL_FRAMES,
	resolveTimeline,
	totalAtFrame,
	validateTimeline,
} from '../src/video1/timeline';

const offset = process.argv[2] !== undefined ? Number(process.argv[2]) : DEFAULT_SYNC_OFFSET_FRAMES;
const T = resolveTimeline(offset);
const rows: string[][] = [];
const row = (section: string, event: string, sec: number, frame: number, word: string) =>
	rows.push([section, event, sec.toFixed(2), String(frame), `${(frame / FPS).toFixed(3)}`, word]);

/* ---- map intro ---- */
row('Map', 'intro starts (spin-in)', TIMELINE.map.introStart, T.map.introStart, 'lead-in to "three different locations"');
const dropWords = ['"three"', '"different"', '"locations"'];
T.map.pinDrops.forEach((f, i) =>
	row('Map', `pin ${i + 1} drops (${['WHOLE FOODS', 'CVS', 'VITAMIN SHOPPE'][i]})`, TIMELINE.map.pinDrops[i], f, `${dropWords[i]} (assumed: one pin per word of "three different locations")`),
);
row('Map', 'route draw starts', TIMELINE.map.routeDraw.start, T.map.routeStart, 'right after "locations"');
row('Map', 'route draw ends', TIMELINE.map.routeDraw.end, T.map.routeEnd, '—');
row('Map', 'exit starts', TIMELINE.map.exit.start, T.map.exitStart, 'hand-off to the board');
row('Map', 'exit ends', TIMELINE.map.exit.end, T.map.exitEnd, '—');

/* ---- board ---- */
row('Board', 'card + tile 1 pop (all 9 tiles blurred)', TIMELINE.board.firstTilePop, T.board.firstTilePop, '"nine"');
BOARD_TILES.forEach((tile, i) => {
	if (i === 0) return;
	const f = T.board.firstTilePop + i * T.board.tileStagger;
	row('Board', `tile ${i + 1} pops (${tile.revealed && tile.name ? tile.name : '??? blurred'})`, TIMELINE.board.firstTilePop + i * TIMELINE.board.tileStagger, Math.round(f), `+${(i * TIMELINE.board.tileStagger).toFixed(2)} s stagger`);
});
row('Board', 'final pulse + "9" badge', TIMELINE.board.finalPulse, T.board.finalPulse, '"ingredients"');
row('Board', 'exit starts', TIMELINE.board.exit.start, T.board.exitStart, '—');
row('Board', 'exit ends', TIMELINE.board.exit.end, T.board.exitEnd, '—');

/* ---- HUD ---- */
row('HUD', 'counter enters ($0.00, 0/9)', TIMELINE.hud.enter, T.hud.enter, '"two hundred dollars"');
row('HUD', 'cash-drain emphasis starts', TIMELINE.hud.cashDrainEmphasis.start, T.hud.drainStart, '"how quickly it disappears"');
row('HUD', 'cash-drain emphasis ends', TIMELINE.hud.cashDrainEmphasis.end, T.hud.drainEnd, '—');

/* ---- pickups ---- */
for (const p of T.pickups) {
	row('Pickup', `${p.id}. ${p.name} chip pops (+$${p.price.toFixed(2)})`, p.at, p.atFrame, `pick-up on camera${p.note ? ` (${p.note})` : ''} — spoken word not specified in the brief`);
	if (TIMELINE.board.revealOnPickup) {
		const rf = revealStartFrame(T, p.id - 1) + BOARD_REVEAL.revealAt;
		row('Pickup', `${p.id}. board pops back up, tile ${p.id} reveals${rf !== p.atFrame + BOARD_REVEAL.revealAt ? ' (deferred until the map slam ends)' : ''}`, p.at + (rf - p.atFrame) / FPS, rf, `reveals ${p.name} and keeps it uncovered (earlier finds stay uncovered too)`);
	}
	row('Pickup', `${p.id}. chip lands → counter rolls to $${p.totalAfter.toFixed(2)}`, p.at + CHIP.landFrames / FPS, p.landFrame, `+0.5 s after the pick-up`);
}
row('HUD', 'total glow pulse', TIMELINE.totalPulse, T.totalPulse, '"seventy one dollars"');

/* ---- map slams ---- */
T.mapSlams.forEach((m, i) => {
	const src = TIMELINE.mapSlams[i];
	row('Map slam', `slam ${m.slam} segment starts`, src.segmentStart, m.start, 'lead-in');
	row('Map slam', `slam ${m.slam} IMPACT (frame 30 of the segment)`, src.segmentStart + 1, m.impact, m.slam === 1 ? '"stop" in "first stop"' : m.slam === 2 ? '"5th ingredient was secured"' : '(see transcript)');
	row('Map slam', `slam ${m.slam} segment ends`, src.segmentStart + 3, m.end, '—');
});

/* ---- markdown ---- */
const pad = (cells: string[]) => `| ${cells.join(' | ')} |`;
const head = ['Section', 'Event', 'Time (s) in source', 'Frame in cut video (after offset)', 'Cut-video time (s)', 'Spoken word / cue'];
const md: string[] = [];
md.push('# Video 1 — sync report', '');
md.push(`Generated by \`npm run sync-report\` from \`src/video1/timeline.ts\` (same source the composition renders from).`, '');
md.push(`- fps **${FPS}**, **${TOTAL_FRAMES}** frames (${(TOTAL_FRAMES / FPS).toFixed(0)} s) — source video is ${SOURCE_FRAMES} frames`);
md.push(`- cuts (source seconds removed): ${CUTS.length ? CUTS.map((c) => `**${c.start.toFixed(2)}–${c.end.toFixed(2)}**`).join(', ') : 'none'}. The "Time (s)" column is SOURCE-video time; "Frame" and "Frame ÷ 30" are in the CUT video.`);
md.push(`- syncOffsetFrames **${offset}** → every graphic hits ${Math.abs(offset)} frame(s) ${offset < 0 ? 'BEFORE' : 'AFTER'} the time in the "Time (s)" column`);
md.push(`- "Frame (after offset)" = round(time × 30) ${offset >= 0 ? '+' : '−'} ${Math.abs(offset)}`, '');
md.push(pad(head), pad(head.map(() => '---')));
rows.sort((a, b) => Number(a[3]) - Number(b[3]));
rows.forEach((r) => md.push(pad(r)));

md.push('', '## Running total (what the counter shows)', '');
md.push('| # | Ingredient | Price | Chip pops (s) | Counter rolls at (frame) | Counter shows |', '| --- | --- | --- | --- | --- | --- |');
T.pickups.forEach((p) => {
	md.push(`| ${p.id} | ${p.name} | $${p.price.toFixed(2)} | ${p.at.toFixed(2)} | ${p.landFrame} (${(p.landFrame / FPS).toFixed(2)} s) | **$${p.totalAfter.toFixed(2)}** — $${(BUDGET - p.totalAfter).toFixed(2)} left, ${p.id}/9 |`);
});
md.push('', `Total at the glow pulse (${TIMELINE.totalPulse.toFixed(2)} s, frame ${T.totalPulse}): **$${totalAtFrame(T, T.totalPulse).toFixed(2)}**`, '');

const warnings = validateTimeline(T);
md.push('## Checks', '');
md.push(warnings.length ? warnings.map((w) => `- ⚠️ ${w}`).join('\n') : '- ✅ running total at "seventy one dollars" is between $70 and $72');
md.push('- ⚠️ Lion\'s Mane $31.49 is a **placeholder** (footage shows a $18.99 tag) — change it in `timeline.ts` only.');
md.push('');

const out = path.join(__dirname, '..', 'sync-report.md');
writeFileSync(out, md.join('\n'));
console.log(`wrote ${path.relative(process.cwd(), out)} (${rows.length} events, offset ${offset})`);
if (warnings.length) {
	console.warn(warnings.map((w) => `WARNING: ${w}`).join('\n'));
}
