/**
 * Writes clips-sync-report.md: every event of the 4 clips with its time (seconds inside the clip) and its frame
 * after syncOffsetFrames, plus the running totals. Also prints the running totals to the console.
 *
 *   npm run clips-report            (offset = default -2)
 *   npx tsx scripts/clips-report.ts -3
 */
import {writeFileSync} from 'node:fs';
import path from 'node:path';
import {CASH_START, CLIP_ORDER, DEFAULT_SYNC_OFFSET_FRAMES, TOTAL_ITEMS, clipChain, resolveClip} from '../src/clips/clips';
import {FPS, ROLL_FRAMES} from '../src/video1/timeline';

const offset = process.argv[2] !== undefined ? Number(process.argv[2]) : DEFAULT_SYNC_OFFSET_FRAMES;
const sec = (f: number) => (f / FPS).toFixed(3);
const md: string[] = [];

md.push('# Clips 6-9 — sync report', '');
md.push('Generated by `npm run clips-report` from `src/clips/clips.ts`. Times are seconds INSIDE each clip.', '');
md.push(`- 1080x1920 design @ ${FPS} fps. Render the 720x1280 clips with \`--scale=0.6666666666666666\` (the render scripts do).`);
md.push(`- syncOffsetFrames **${offset}**: every graphic lands ${Math.abs(offset)} frame(s) ${offset < 0 ? 'BEFORE' : 'AFTER'} the time in the "Time (s)" column.`);
md.push('- The counter rolls when the chip lands = pickup + 0.5 s (15 frames). The HUD is already on screen at frame 0.', '');

for (const id of CLIP_ORDER) {
	const R = resolveClip(id, {syncOffsetFrames: offset});
	const c = R.cfg;
	const p = R.pickup;
	const over = p.totalAfter > CASH_START;
	const rows: [string, number, number, string][] = [
		['clip starts — HUD already on screen', 0, 0, `$${p.totalBefore.toFixed(2)}, ${c.itemNumber - 1}/${TOTAL_ITEMS}, $${(CASH_START - p.totalBefore).toFixed(2)} left`],
		[`PickupChip pops: ${c.ingredient} +$${c.price.toFixed(2)}`, c.pickupAt, p.atFrame, 'pickup moment (then flies up for 0.5 s)'],
		['chip lands -> counter starts rolling + stamp sound', c.pickupAt + 0.5, p.landFrame, `${c.itemNumber}/${TOTAL_ITEMS}; tick sound at frame ${p.landFrame + 3}`],
		['counter finished rolling', 0, p.landFrame + ROLL_FRAMES, `$${p.totalAfter.toFixed(2)}, ${over ? `SHORT $${(p.totalAfter - CASH_START).toFixed(2)}` : `$${(CASH_START - p.totalAfter).toFixed(2)} left`}`],
	];
	if (c.finale) {
		rows.push(['finale: 9/9 gold burst + glow pulse', c.pickupAt + 0.5, p.landFrame, 'rings + rays around n/9, glow pulse (about 1 s)']);
		if (over) rows.push(['OVER $' + CASH_START + ' badge pops in', 0, p.landFrame + 6, 'bar empty, label reads SHORT']);
	}
	rows.push(['clip ends', c.durationSeconds, R.durationInFrames, 'frames ' + R.durationInFrames]);
	if (c.extendedSeconds) rows.push([`clip ends (extended prop on)`, c.extendedSeconds, Math.round(c.extendedSeconds * FPS), 'frames ' + Math.round(c.extendedSeconds * FPS)]);
	md.push(`## ${c.compositionId} — ${c.title}`, '');
	md.push(`File: \`public/clips/${c.file}\`   (item ${c.itemNumber}/${TOTAL_ITEMS})`, '');
	md.push('| Event | Time (s) in clip | Frame (after offset) | Frame ÷ 30 (s) | Notes |', '| --- | --- | --- | --- | --- |');
	for (const [e, t, f, n] of rows) md.push(`| ${e} | ${t ? t.toFixed(2) : '—'} | ${f} | ${sec(f)} | ${n} |`);
	md.push('');
}

const {rows, warnings} = clipChain();
md.push('## Running total after each clip', '');
md.push('| Clip | Item | Start total | + Price | End total | Cash left |', '| --- | --- | --- | --- | --- | --- |');
for (const r of rows) md.push(`| ${r.title} | ${r.item}/${TOTAL_ITEMS} | $${r.start.toFixed(2)} | +$${r.price.toFixed(2)} | **$${r.end.toFixed(2)}** | ${r.left >= 0 ? `$${r.left.toFixed(2)}` : `SHORT $${(-r.left).toFixed(2)}`} |`);
md.push('');
md.push('## Checks', '');
md.push(warnings.length ? warnings.map((w) => `- ⚠️ ${w}`).join('\n') : '- ✅ startTotals chain correctly from clip to clip');
md.push('- ⚠️ The chain starts from $75.16, the Video 1 total, which includes the PLACEHOLDER Lion\'s Mane price ($31.49). If that changes, update `startTotal` of BetaAlanine.');
md.push('');

for (const r of rows) {
	console.log(`${r.title.padEnd(13)} $${r.start.toFixed(2)} + $${r.price.toFixed(2)} = $${r.end.toFixed(2)}  (${r.item}/${TOTAL_ITEMS}, ${r.left >= 0 ? '$' + r.left.toFixed(2) + ' left' : 'SHORT $' + (-r.left).toFixed(2)})`);
}
for (const w of warnings) console.warn('WARNING:', w);

const out = path.join(__dirname, '..', 'clips-sync-report.md');
writeFileSync(out, md.join('\n'));
console.log(`wrote ${path.relative(process.cwd(), out)}`);
